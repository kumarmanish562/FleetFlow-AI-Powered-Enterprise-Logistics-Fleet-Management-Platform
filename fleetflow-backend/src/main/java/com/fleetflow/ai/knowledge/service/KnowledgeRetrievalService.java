package com.fleetflow.ai.knowledge.service;

import com.fleetflow.ai.knowledge.dto.KnowledgeSource;
import com.fleetflow.ai.knowledge.model.DocumentStatus;
import com.fleetflow.ai.knowledge.repository.KnowledgeDocumentRepository;
import com.fleetflow.ai.knowledge.security.KnowledgePrincipalService;
import org.springframework.ai.vectorstore.SearchRequest;
import org.springframework.ai.vectorstore.VectorStore;
import org.springframework.ai.vectorstore.filter.FilterExpressionBuilder;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.security.core.Authentication;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.transaction.annotation.Isolation;
import java.util.*;

@Service
@ConditionalOnProperty(prefix = "fleetflow.knowledge", name = "enabled", havingValue = "true")
public class KnowledgeRetrievalService {
    private final KnowledgeDocumentRepository documents;
    private final KnowledgePrincipalService principals;
    private final VectorStore vectors;
    private final int topK;
    private final int maxContextChunks;
    private final double threshold;

    @Autowired
    public KnowledgeRetrievalService(KnowledgeDocumentRepository documents, KnowledgePrincipalService principals,
                                     VectorStore vectors,
                                     @Value("${fleetflow.knowledge.retrieval.top-k:5}") int topK,
                                     @Value("${fleetflow.knowledge.retrieval.similarity-threshold:0.7}") double threshold,
                                     @Value("${fleetflow.knowledge.retrieval.max-context-chunks:6}") int maxContextChunks) {
        this.documents = documents; this.principals = principals; this.vectors = vectors;
        this.topK = Math.max(1, Math.min(20, topK)); this.threshold = Math.max(0, Math.min(1, threshold));
        this.maxContextChunks = Math.max(1, Math.min(10, maxContextChunks));
    }

    public KnowledgeRetrievalService(KnowledgeDocumentRepository documents, KnowledgePrincipalService principals,
                                     VectorStore vectors, int topK, double threshold) {
        this(documents, principals, vectors, topK, threshold, 6);
    }

    @Transactional(readOnly = true, isolation = Isolation.REPEATABLE_READ)
    public List<KnowledgeSource> retrieve(String query, Authentication authentication) {
        var principal = principals.resolve(authentication);
        var allowed = documents.findByOrganizationIdAndStatus(principal.organizationId(), DocumentStatus.INDEXED)
                .stream().filter(d -> d.getAccessRoles() != null &&
                        d.getAccessRoles().stream().anyMatch(principal.roles()::contains)).toList();
        if (allowed.isEmpty()) return List.of();
        if (allowed.size() > 2000) throw new IllegalStateException("Too many authorized knowledge documents for one query");
        Set<String> allowedIds = new HashSet<>();
        for (var d : allowed) allowedIds.add(d.getId().toString());
        // UUIDs are generated by the server, and this filter is applied by pgvector
        // during similarity search before any document text is returned.
        FilterExpressionBuilder b = new FilterExpressionBuilder();
        var filter = b.and(b.eq("organizationId", principal.organizationId().toString()),
                b.and(b.eq("active", true), b.in("documentId", new ArrayList<>(allowedIds)))).build();
        var results = vectors.similaritySearch(SearchRequest.builder().query(query).topK(topK)
                .similarityThreshold(threshold).filterExpression(filter).build());
        if (results == null) return List.of();
        List<KnowledgeSource> sources = new ArrayList<>();
        for (var chunk : results.stream().limit(maxContextChunks).toList()) {
            Map<String, Object> metadata = chunk.getMetadata();
            String id = String.valueOf(metadata.get("documentId"));
            if (!allowedIds.contains(id)) continue;
            Integer page = metadata.get("pageNumber") instanceof Number n ? n.intValue() : null;
            String text = chunk.getText() == null ? "" : chunk.getText();
            sources.add(new KnowledgeSource(UUID.fromString(id), String.valueOf(metadata.get("filename")),
                    String.valueOf(metadata.get("version")), page,
                    text.substring(0, Math.min(text.length(), 1200)), chunk.getScore(), chunk.getId()));
        }
        return List.copyOf(sources);
    }
}
